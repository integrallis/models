#!/bin/bash
# Generate the user-data bootstrap for one shard, and upload the worker it fetches.
#
# Why this exists. `run-shards.sh` passes `--user-data file://$BOOTSTRAPS/ud-boot-$SHARD.sh`, and
# no such file was ever committed: every campaign generated one by hand, which is the same gap that
# left `qual-worker-two-arm.sh` in a scratch directory for all of 2026-09. The boot file is now
# derived from the committed worker by this script, so what ran is reconstructible from a shard
# number and a commit.
#
# Why curl and a presigned URL, rather than `aws s3 cp`:
#
#   - The worker is ~31 KB and user-data is capped at 16384 bytes, so it cannot be inlined.
#   - The AMI has no aws CLI. `apt-cache policy awscli` reports "Candidate: (none)" on Ubuntu
#     24.04.5, and installing it is the first thing the worker itself does. A bootstrap that
#     called `aws s3 cp` would fail before the tooling it needs exists -- the failure that killed
#     every worker in one campaign.
#   - A presigned GET needs no credentials on the box, is scoped to one object, and expires. The
#     instance role still covers everything the worker does afterwards.
#
# The worker is uploaded under its commit sha, so a boot file names the exact script it fetched and
# a later run cannot silently get a different one. Per the runbook, a sha baked into a deployed
# object is frozen: regenerate under a new sha rather than overwriting.
set -euo pipefail

SHARD=${SHARD:?SHARD is required}
QUAL_PAYLOAD=${QUAL_PAYLOAD:?QUAL_PAYLOAD is required}
QUAL_KERNELS=${QUAL_KERNELS:?QUAL_KERNELS is required}
QUAL_BACKEND_VERSION=${QUAL_BACKEND_VERSION:?QUAL_BACKEND_VERSION is required}
BUCKET=${BUCKET:-models-qual-077051030817}
EXPIRY=${EXPIRY:-43200}
OUT_DIR=${OUT_DIR:-$(cd "$(dirname "$0")" && pwd)}

S=$(cd "$(dirname "$0")" && pwd)
cd "$S/../.."

# The committed worker, never the working copy: an edited copy is what made the 2026-10-09 reports
# describe a build nobody had.
WORKER_SHA=$(git rev-parse HEAD)
WORKER_KEY="payload/qual-worker-two-arm-${WORKER_SHA:0:12}.sh"
TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT
git show "HEAD:scripts/fleet/qual-worker-two-arm.sh" > "$TMP"

if aws s3 ls "s3://$BUCKET/$WORKER_KEY" >/dev/null 2>&1; then
  echo "worker already uploaded at $WORKER_KEY (frozen; not overwriting)"
else
  aws s3 cp "$TMP" "s3://$BUCKET/$WORKER_KEY" --only-show-errors
  echo "uploaded worker to s3://$BUCKET/$WORKER_KEY"
fi

URL=$(aws s3 presign "s3://$BUCKET/$WORKER_KEY" --expires-in "$EXPIRY")

BOOT="$OUT_DIR/ud-boot-$SHARD.sh"
cat > "$BOOT" <<BOOTSTRAP
#!/bin/bash
# Generated by scripts/fleet/make-boot.sh for shard $SHARD. Do not edit by hand.
# worker: $WORKER_KEY (models @ $WORKER_SHA)
set -u
export SHARD=$SHARD
export QUAL_PAYLOAD=$QUAL_PAYLOAD
export QUAL_KERNELS=$QUAL_KERNELS
export QUAL_BACKEND_VERSION=$QUAL_BACKEND_VERSION

# The console is the only channel that reports a failure happening before any tooling exists, so
# say() writes there and nowhere else until the worker takes over.
say() { printf '[boot %s] %s\n' "\$(date -u +%H:%M:%S)" "\$*" > /dev/console 2>/dev/null; }
say "fetching worker for shard $SHARD"

if ! curl -fsSL --retry 5 --retry-delay 5 --retry-connrefused --max-time 180 \\
     "$URL" -o /root/qual-worker.sh; then
  say "FATAL could not fetch the worker; terminating rather than idling"
  shutdown -h now
  exit 1
fi

# A truncated or HTML error body would otherwise be executed as a shell script.
if ! head -1 /root/qual-worker.sh | grep -q '^#!/bin/bash'; then
  say "FATAL fetched object is not the worker script; terminating"
  shutdown -h now
  exit 1
fi

say "worker fetched (\$(wc -c < /root/qual-worker.sh) bytes); handing over"
exec bash /root/qual-worker.sh
BOOTSTRAP

BYTES=$(wc -c < "$BOOT")
echo "wrote $BOOT ($BYTES bytes)"
if [ "$BYTES" -ge 16384 ]; then
  echo "FATAL boot file is $BYTES bytes; user-data is capped at 16384" >&2
  exit 1
fi
echo "presigned URL expires in ${EXPIRY}s"
