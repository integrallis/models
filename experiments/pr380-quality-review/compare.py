#!/usr/bin/env python3
"""Generate comparable score tables from the three unmodified MFCQI JSON report sets."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ARMS = ("main", "before", "after")
reports = {
    arm: {p.stem: json.loads(p.read_text()) for p in (HERE / "results" / arm).glob("*.json")}
    for arm in ARMS
}
assert reports["main"].keys() == reports["before"].keys() == reports["after"].keys()


def table(scopes):
    lines = [
        "| Scope | Main | Original PR | Reviewed PR | Reviewed − main | Reviewed − original |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for scope in scopes:
        main, before, after = (100 * reports[arm][scope]["mfcqi_score"] for arm in ARMS)
        lines.append(
            f"| {scope} | {main:.4f} | {before:.4f} | {after:.4f} | {after-main:+.4f} | {after-before:+.4f} |"
        )
    return "\n".join(lines)


changed = ["release"] + sorted(
    scope for scope in reports["main"] if scope != "release"
    and len({reports[arm][scope]["mfcqi_score"] for arm in ARMS}) > 1
)
lines = [
    "# MFCQI comparison",
    "",
    "Generated by `python3 experiments/pr380-quality-review/compare.py` from the raw JSON reports. "
    "Scores are multiplied by 100; deltas are score points. Higher is better. "
    "Release is the CI aggregate of ten published modules, not an average of module scores.",
    "",
    "## Changed scopes",
    "",
    table(changed),
    "",
    "## Release metric components",
    "",
    "Normalized analyzer components, on their original 0–1 scale. All three arms use identical weights and configuration.",
    "",
    "| Component | Main | Original PR | Reviewed PR | Reviewed − main |",
    "|---|---:|---:|---:|---:|",
]
for metric in reports["main"]["release"]:
    if metric == "mfcqi_score":
        continue
    main, before, after = (reports[arm]["release"][metric] for arm in ARMS)
    lines.append(f"| {metric} | {main:.6f} | {before:.6f} | {after:.6f} | {after-main:+.6f} |")
lines.extend(["", "## All scopes", "", table(sorted(reports["main"])), ""])
(HERE / "COMPARISON.md").write_text("\n".join(lines))
print(table(changed))
